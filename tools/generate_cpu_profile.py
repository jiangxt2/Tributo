"""Derive the Linux arm64 Torch CPU lock without changing the SDK lock."""

from __future__ import annotations

import hashlib
import json
import shutil
import subprocess
import tomllib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
PROFILE = ROOT / "docker/tributo-runtime/cpu"
TORCH_VERSION = "2.13.0+cpu"
TORCH_SHA256 = "6f307c2c32d764ffc6ff6893b801fad6d4752f3e67966cb8abf1843427c02604"
TORCH_URL = (
    "https://download-r2.pytorch.org/whl/cpu/"
    "torch-2.13.0%2Bcpu-cp312-cp312-manylinux_2_28_aarch64.whl"
)


def main() -> None:
    project = (ROOT / "pyproject.toml").read_text()
    original = tomllib.loads(project)
    if original["project"]["requires-python"] != ">=3.12,<3.14":
        raise ValueError("Review the CPU Python baseline before regenerating")
    if "torch" in original.get("tool", {}).get("uv", {}).get("sources", {}):
        raise ValueError("Review the existing Torch source before regenerating")
    if "[tool.uv]" in project:
        raise ValueError("Review uv environment settings before regenerating")
    project = project.replace(
        'requires-python = ">=3.12,<3.14"',
        'requires-python = ">=3.12,<3.13"',
        1,
    ).replace(
        "[tool.uv.sources]",
        f'[tool.uv.sources]\ntorch = {{ url = "{TORCH_URL}" }}',
        1,
    )
    project += (
        "\n[tool.uv]\n"
        "package = false\n"
        "environments = [\"sys_platform == 'linux' and platform_machine == 'aarch64'\"]\n"
    )
    PROFILE.mkdir(parents=True, exist_ok=True)
    (PROFILE / "pyproject.toml").write_text(project)
    (PROFILE / "README.md").write_text(
        "# Linux arm64 CPU dependency profile\n\n"
        "Generated by tools/generate_cpu_profile.py from the SDK metadata and lock.\n"
        "This is a dependency resolution profile, not a separately published SDK.\n"
        "Use tools/host_uv_export.py --cpu to export its verified dependencies.\n"
    )
    shutil.copy2(ROOT / "uv.lock", PROFILE / "uv.lock")
    subprocess.run(
        ["uv", "lock", "--project", str(PROFILE), "--python", "3.12"],
        cwd=ROOT,
        check=True,
    )
    baseline = tomllib.loads((ROOT / "uv.lock").read_text())["package"]
    resolved = tomllib.loads((PROFILE / "uv.lock").read_text())["package"]
    baseline_versions: dict[str, set[str]] = {}
    for item in baseline:
        baseline_versions.setdefault(item["name"], set()).add(item["version"])
    for item in resolved:
        if item["name"] == "torch":
            if item["version"] != TORCH_VERSION:
                raise ValueError("CPU lock did not select the exact Torch build")
            if {wheel["hash"] for wheel in item.get("wheels", [])} != {
                f"sha256:{TORCH_SHA256}"
            }:
                raise ValueError("CPU Wheel hash differs from the official artifact")
        elif item["version"] not in baseline_versions.get(item["name"], set()):
            raise ValueError(f"Unexpected dependency version drift: {item['name']}")

    def digest(path: Path) -> str:
        return hashlib.sha256(path.read_bytes()).hexdigest()

    manifest = {
        "schema_version": 1,
        "platform": "linux/arm64",
        "python_version": "3.12",
        "torch_version": TORCH_VERSION,
        "torch_url": TORCH_URL,
        "torch_sha256": TORCH_SHA256,
        "inputs": {name: digest(ROOT / name) for name in ("pyproject.toml", "uv.lock")},
        "files": {
            name: digest(PROFILE / name)
            for name in ("pyproject.toml", "uv.lock", "README.md")
        },
    }
    (PROFILE / "profile.json").write_text(json.dumps(manifest, indent=2) + "\n")
    print(json.dumps(manifest, indent=2))


if __name__ == "__main__":
    main()
